def _orden(nombre: str) -> str:
    return "".join(c for c in unicodedata.normalize("NFKD", nombre)
                   if not unicodedata.combining(c)).upper()


COMERCIALIZADORAS = sorted({n.strip() for n in LISTA.splitlines() if n.strip()}, key=_orden)


def opciones(actual: str = "") -> list:
    """Opciones del desplegable: vacío, la lista y, si la oferta tiene otra (guardada antes),
    también esa."""
    extra = [actual] if actual and actual not in COMERCIALIZADORAS else []
    return [""] + extra + COMERCIALIZADORAS
